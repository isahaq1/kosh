/**
 * Typed views of the business apps' models (modules/*): `pnpm generate:models` writes `src/.kosh/schema.d.ts` and
 * `src/.kosh/bindings.ts` next to each app's `src/module.ts`; `--check` fails when one is stale (CI, `pnpm lint`).
 *
 * The views come from Shutro's generator (the ORM's own type generation, RFC 0002 of Shutro), run here through
 * Kosh's one Shutro gateway (`@kosh/server/orm`, `loadCodegen`). Kosh keeps them in the app, never in Shutro, and
 * points their imports at `@kosh/server/orm`, so apps import the ORM only through Kosh. A module file imports its
 * definition API from `./.kosh/bindings.js`: computes, checks and onchange handlers are typed to the models it sees.
 *
 * Run with the `@kosh/source` condition (the script in package.json does), so the framework modules it depends on
 * (`base`, ...) load from their sources, the same objects the apps import.
 */
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCodegen } from '../packages/server/src/orm.ts';

const root = join(fileURLToPath(import.meta.url), '..', '..');
const check = process.argv.includes('--check');

/**
 * Framework modules the apps may depend on, and the package exporting each (their views are not written: they are
 * not apps). Shutro's generator needs the source of every module in the dependency graph.
 */
const FRAMEWORK: Readonly<Record<string, string>> = {
  'packages/server/src/auth/base.ts': '@kosh/server',
  'packages/storage/src/models.ts': '@kosh/storage',
  'packages/messaging/src/models.ts': '@kosh/messaging',
  'packages/permissions/src/models.ts': '@kosh/permissions',
  'packages/reporting/src/models.ts': '@kosh/reporting',
};
const apps = existsSync(join(root, 'modules'))
  ? readdirSync(join(root, 'modules'))
      .map((name) => `modules/${name}/src/module.ts`)
      .filter((file) => existsSync(join(root, file)))
      .sort()
  : [];

/** Until a module's view exists, its module file imports this stand-in (same exports, loosely typed). */
const STUB = `// Placeholder until \`pnpm generate:models\` writes the typed view of this module.
export { defineModel, defineModule, extendModel, f, replace } from '@kosh/server/orm';
import { definitions } from '@kosh/server/orm';

const helpers = definitions<never>();
export const compute = helpers.compute;
export const check = helpers.check;
export const onchange = helpers.onchange;
export const records = helpers.records;
export const method = helpers.method;
export const record = helpers.record;
export const override = helpers.override;
export const ref = helpers.ref;
`;
for (const file of apps) {
  const bindings = join(root, dirname(file), '.kosh', 'bindings.ts');
  if (!existsSync(bindings)) {
    mkdirSync(dirname(bindings), { recursive: true });
    writeFileSync(bindings, STUB);
  }
}

/**
 * The package that exports a module file's Shutro module (`@kosh/server` exports `baseShutro`, `@kosh/<app>` its
 * app's): views refer to other modules by package, not by a path into another package's sources.
 */
function packageOf(file: string): string | undefined {
  const framework = FRAMEWORK[file];
  if (framework !== undefined) return framework;
  const app = /^modules\/([a-z0-9-]+)\/src\/module\.ts$/.exec(file);
  return app === null ? undefined : `@kosh/${app[1]}`;
}

/** Kosh's spelling of a generated file: imports through Kosh, other modules by package, and who generated it. */
function rewrite(content: string, outDir: string): string {
  return content
    .replace(/import\('(\.[^']+)'\)/g, (all, path: string) => {
      const file = relative(root, join(root, outDir, path.replace(/\.js$/, '.ts')))
        .split(sep)
        .join('/');
      const pkg = packageOf(file);
      return pkg === undefined || file.startsWith(`${dirname(dirname(outDir))}/`)
        ? all
        : `import('${pkg}')`;
    })
    .replace(/from 'shutro'/g, "from '@kosh/server/orm'")
    .replace(
      /^\/\/ GENERATED by `shutro generate`\./m,
      '// GENERATED by `pnpm generate:models` (Shutro’s generator).',
    );
}

const { generate } = await loadCodegen();
const out = mkdtempSync(join(tmpdir(), 'kosh-models-'));
try {
  await generate({
    config: { modules: [...Object.keys(FRAMEWORK), ...apps].map((f) => join(root, f)) },
    cwd: root,
    outRoot: out,
  });
  const stale: string[] = [];
  for (const file of apps) {
    const generated = join(out, dirname(file), '.shutro');
    for (const name of readdirSync(generated)) {
      const target = join(root, dirname(file), '.kosh', name);
      const content = rewrite(
        readFileSync(join(generated, name), 'utf8'),
        join(dirname(file), '.kosh').split(sep).join('/'),
      );
      const current = existsSync(target) ? readFileSync(target, 'utf8') : undefined;
      if (current === content) continue;
      const shown = relative(root, target).split(sep).join('/');
      if (check) stale.push(shown);
      else {
        mkdirSync(dirname(target), { recursive: true });
        writeFileSync(target, content);
        process.stdout.write(`wrote ${shown}\n`);
      }
    }
  }
  if (stale.length > 0) {
    process.stderr.write(
      `Stale model views (run pnpm generate:models):\n${stale.map((s) => `  ${s}`).join('\n')}\n`,
    );
    process.exitCode = 1;
  } else process.stdout.write(`generate-models: ${apps.length} app(s) up to date\n`);
} finally {
  rmSync(out, { recursive: true, force: true });
}
