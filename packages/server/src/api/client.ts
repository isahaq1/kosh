/**
 * The typed client generator (RFC 0002 §6.4, `kosh generate client`): turns the OpenAPI document of an installed
 * module set into one self-contained TypeScript module, with no imports, that browsers and Node both run:
 *
 * - an interface per model (read, create, update) and per shared schema (Problem, Money, AggregateQuery, ...);
 * - `Models`, the map from model name to those types and its transitions;
 * - `createClient()`: typed calls for every generated route and the auth routes, sessions by cookie (with the
 *   CSRF header) or Bearer token, `KoshApiError` carrying the RFC 9457 problem.
 *
 * Generated code is deterministic (sorted), so regenerating without changes gives the same file.
 */

type Schema = Readonly<Record<string, unknown>>;

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

function propertyName(key: string): string {
  return IDENTIFIER.test(key) ? key : JSON.stringify(key);
}

function refName(ref: string): string {
  return ref.replace(/^#\/components\/schemas\//, '');
}

function asSchema(value: unknown): Schema {
  return typeof value === 'object' && value !== null ? (value as Schema) : {};
}

/** The TypeScript type of a JSON Schema (the subset `openApiDocument` emits). */
export function typeOf(schema: Schema, indent = ''): string {
  if (typeof schema['$ref'] === 'string') return refName(schema['$ref']);
  if (Array.isArray(schema['oneOf']))
    return schema['oneOf'].map((s) => typeOf(asSchema(s), indent)).join(' | ');
  if (Array.isArray(schema['enum']))
    return schema['enum'].map((v) => JSON.stringify(v)).join(' | ');
  const types = Array.isArray(schema['type']) ? schema['type'] : [schema['type']];
  return types
    .map((type) => {
      switch (type) {
        case 'string':
          return 'string';
        case 'integer':
        case 'number':
          return 'number';
        case 'boolean':
          return 'boolean';
        case 'null':
          return 'null';
        case 'array': {
          const item = typeOf(asSchema(schema['items']), indent);
          return /^[\w.]+$/.test(item) ? `${item}[]` : `(${item})[]`;
        }
        case 'object':
          return schema['properties'] === undefined
            ? 'Record<string, unknown>'
            : objectType(schema, indent);
        default:
          return 'unknown';
      }
    })
    .join(' | ');
}

function doc(schema: Schema, indent: string): string {
  const parts = [schema['title'], schema['description']].filter(
    (p): p is string => typeof p === 'string' && p !== '',
  );
  return parts.length === 0 ? '' : `${indent}/** ${parts.join(': ').replaceAll('*/', '* /')} */\n`;
}

function objectType(schema: Schema, indent: string): string {
  const properties = asSchema(schema['properties']);
  const required = new Set(
    Array.isArray(schema['required']) ? (schema['required'] as string[]) : [],
  );
  const inner = `${indent}  `;
  const lines = Object.entries(properties).map(([key, value]) => {
    const s = asSchema(value);
    const optional = required.has(key) ? '' : '?';
    return `${doc(s, inner)}${inner}${propertyName(key)}${optional}: ${typeOf(s, inner)};`;
  });
  return lines.length === 0 ? 'Record<string, never>' : `{\n${lines.join('\n')}\n${indent}}`;
}

/** Model name → schema name and transitions, read back from the generated paths. */
function modelsOf(paths: Schema): { name: string; schema: string; transitions: string[] }[] {
  const models = new Map<string, { name: string; schema: string; transitions: string[] }>();
  for (const [path, item] of Object.entries(paths)) {
    const list = /^\/api\/v1\/models\/([^/{}]+)$/.exec(path);
    const operation = asSchema(asSchema(item)['get'])['operationId'];
    if (list?.[1] !== undefined && typeof operation === 'string' && operation.startsWith('list'))
      models.set(list[1], { name: list[1], schema: operation.slice(4), transitions: [] });
  }
  for (const path of Object.keys(paths)) {
    const t = /^\/api\/v1\/models\/([^/{}]+)\/\{id\}\/transitions\/([^/{}]+)$/.exec(path);
    if (t?.[1] !== undefined && t[2] !== undefined) models.get(t[1])?.transitions.push(t[2]);
  }
  return [...models.values()]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((m) => ({ ...m, transitions: m.transitions.sort() }));
}

/** Generates the client module for an OpenAPI document produced by `openApiDocument`. */
export function generateClient(document: Schema): string {
  const info = asSchema(document['info']);
  const schemas = asSchema(asSchema(document['components'])['schemas']);
  const models = modelsOf(asSchema(document['paths']));
  const out: string[] = [];
  out.push(
    `// Generated by \`kosh generate client\` from ${JSON.stringify(String(info['title'] ?? 'Kosh API'))} ${String(info['version'] ?? '')}. Do not edit: regenerate.`,
    '',
    '// ------------------------------------------------------------------------------------------------- schemas',
    '',
  );
  for (const name of Object.keys(schemas).sort()) {
    const schema = asSchema(schemas[name]);
    const body = typeOf(schema);
    const declaration = body.startsWith('{')
      ? `export interface ${name} ${body}`
      : `export type ${name} = ${body};`;
    out.push(`${doc(schema, '')}${declaration}`, '');
  }
  out.push(
    '// -------------------------------------------------------------------------------------------------- models',
    '',
    '/** Every model this API serves: its read, create and update shapes, and its state transitions. */',
    'export interface Models {',
  );
  for (const m of models)
    out.push(
      `  ${JSON.stringify(m.name)}: {`,
      `    record: ${m.schema};`,
      `    create: ${m.schema}Create;`,
      `    update: ${m.schema}Update;`,
      `    transitions: ${m.transitions.length === 0 ? 'never' : m.transitions.map((t) => JSON.stringify(t)).join(' | ')};`,
      '  };',
    );
  out.push(
    '}',
    '',
    '/** The model names, at runtime. */',
    `export const MODEL_NAMES: readonly ModelName[] = ${JSON.stringify(models.map((m) => m.name))};`,
    '',
    RUNTIME,
  );
  return `${out
    .filter((line, i, all) => !(line === '' && all[i - 1] === ''))
    .join('\n')
    .trimEnd()}\n`;
}

/** The runtime part of the generated module (plain TypeScript, erasable syntax only). */
const RUNTIME = `// ------------------------------------------------------------------------------------------------- runtime

export type ModelName = keyof Models;
export type RecordOf<M extends ModelName> = Models[M]['record'];
export type CreateOf<M extends ModelName> = Models[M]['create'];
export type UpdateOf<M extends ModelName> = Models[M]['update'];
export type TransitionOf<M extends ModelName> = Models[M]['transitions'];

/** The fields a list returns: all default fields, or \`id\` plus the requested ones. */
export type Selected<R, K extends keyof R> = [K] extends [never] ? R : Pick<R, K | ('id' & keyof R)>;

/** Search parameters. \`filter\` is a Shutro domain, e.g. \`{ name: { ilike: 'acme%' } }\`. */
export interface ListQuery<R, K extends keyof R> {
  readonly filter?: Readonly<Record<string, unknown>>;
  readonly order?: string | readonly string[];
  readonly fields?: readonly K[];
  readonly limit?: number;
  readonly offset?: number;
  readonly count?: boolean;
}

export interface ListResult<T> {
  readonly items: T[];
  /** With \`count: true\`. */
  readonly count?: number;
}

/** A record with its ETag, to send back as \`ifMatch\` (412 when it changed since). */
export interface Versioned<T> {
  readonly record: T;
  readonly etag: string | null;
}

export interface WriteOptions {
  /** A retried request with the same key returns the first response. */
  readonly idempotencyKey?: string;
  /** The ETag read with the record. */
  readonly ifMatch?: string;
}

/** The caller's view of a model (\`GET /api/v1/meta/{model}\`). */
export interface ModelMeta {
  readonly name: string;
  readonly label: string;
  readonly operations: Readonly<Record<'read' | 'write' | 'create' | 'unlink' | 'export' | 'import', boolean>>;
  readonly transitions: readonly string[];
  readonly onchange: readonly string[];
  readonly fields: readonly {
    readonly key: string;
    readonly kind: string;
    readonly label: string;
    readonly required: boolean;
    readonly readonly: boolean;
    readonly target?: string;
    readonly options?: readonly { readonly value: string; readonly label: string }[];
  }[];
}

/** Typed calls on one model. */
export interface ModelClient<M extends ModelName> {
  list<K extends keyof RecordOf<M> & string = never>(
    query?: ListQuery<RecordOf<M>, K>,
  ): Promise<ListResult<Selected<RecordOf<M>, K>>>;
  get(id: number): Promise<Versioned<RecordOf<M>>>;
  create(values: CreateOf<M>, options?: WriteOptions): Promise<Versioned<RecordOf<M>>>;
  update(id: number, values: UpdateOf<M>, options?: WriteOptions): Promise<Versioned<RecordOf<M>>>;
  delete(id: number, options?: WriteOptions): Promise<void>;
  transition(id: number, name: TransitionOf<M>, options?: WriteOptions): Promise<Versioned<RecordOf<M>>>;
  aggregate(query: AggregateQuery): Promise<Record<string, unknown>[]>;
  onchange(input: OnchangeInput): Promise<OnchangeResult>;
  meta(): Promise<ModelMeta>;
}

export interface SignIn {
  readonly token: string;
  readonly csrfToken: string;
  readonly twoFactorRequired: boolean;
}

export interface CurrentUser {
  readonly id: number;
  readonly login: string;
  readonly name: string;
  readonly company: number | null;
  readonly companies: readonly number[];
  readonly twoFactorEnabled: boolean;
}

/** The auth routes; sign-in keeps the session (token or CSRF token) in the client. */
export interface AuthClient {
  login(login: string, password: string): Promise<SignIn>;
  verifyTwoFactor(code: string): Promise<void>;
  logout(): Promise<void>;
  me(): Promise<CurrentUser>;
  setupTwoFactor(): Promise<{ readonly secret: string; readonly otpauthUri: string }>;
  enableTwoFactor(code: string): Promise<{ readonly recoveryCodes: readonly string[] }>;
  disableTwoFactor(password: string, code: string): Promise<void>;
  changePassword(current: string, next: string): Promise<void>;
}

export interface KoshClient {
  model<M extends ModelName>(name: M): ModelClient<M>;
  readonly auth: AuthClient;
  /** The company of later requests (\`X-Company\`); \`undefined\`: the user's default. */
  setCompany(company: number | undefined): void;
}

export interface ClientOptions {
  /** Default: same origin. */
  readonly baseUrl?: string;
  /** \`cookie\` (browsers: the session cookie plus the CSRF header) or \`bearer\` (scripts, servers). Default: cookie. */
  readonly session?: 'cookie' | 'bearer';
  /** An existing session token (bearer) or CSRF token (cookie). */
  readonly token?: string;
  readonly csrfToken?: string;
  readonly company?: number;
  readonly headers?: Readonly<Record<string, string>>;
  readonly fetch?: typeof fetch;
}

/** A refused request: the RFC 9457 problem the server returned. */
export class KoshApiError extends Error {
  readonly status: number;
  readonly problem: Problem;
  constructor(problem: Problem) {
    super(problem.hint === undefined ? problem.detail : \`\${problem.detail} \${problem.hint}\`);
    this.name = 'KoshApiError';
    this.status = problem.status;
    this.problem = problem;
  }
}

interface Call {
  readonly query?: Readonly<Record<string, string | undefined>>;
  readonly body?: unknown;
  readonly headers?: Readonly<Record<string, string | undefined>>;
}

/** Creates a client. */
export function createClient(options: ClientOptions = {}): KoshClient {
  const base = (options.baseUrl ?? '').replace(/\\/$/, '');
  const doFetch = options.fetch ?? globalThis.fetch.bind(globalThis);
  const mode = options.session ?? 'cookie';
  let token = options.token;
  let csrf = options.csrfToken;
  let company = options.company;

  async function call<T>(method: string, path: string, c: Call = {}): Promise<{ body: T; headers: Headers }> {
    const params = new URLSearchParams();
    for (const [k, v] of Object.entries(c.query ?? {})) if (v !== undefined) params.set(k, v);
    const headers: Record<string, string> = { accept: 'application/json', ...options.headers };
    for (const [k, v] of Object.entries(c.headers ?? {})) if (v !== undefined) headers[k] = v;
    if (c.body !== undefined) headers['content-type'] = 'application/json';
    if (company !== undefined) headers['x-company'] = String(company);
    if (mode === 'bearer' && token !== undefined) headers['authorization'] = \`Bearer \${token}\`;
    if (mode === 'cookie' && csrf !== undefined && method !== 'GET') headers['x-csrf-token'] = csrf;
    const search = params.size === 0 ? '' : \`?\${params.toString()}\`;
    const response = await doFetch(\`\${base}\${path}\${search}\`, {
      method,
      headers,
      ...(c.body === undefined ? {} : { body: JSON.stringify(c.body) }),
      ...(mode === 'cookie' ? { credentials: 'include' as const } : {}),
    });
    const text = await response.text();
    let body: unknown = null;
    try {
      body = text === '' ? null : JSON.parse(text);
    } catch {
      body = null;
    }
    if (!response.ok) {
      const p = typeof body === 'object' && body !== null && 'type' in body ? (body as Problem) : undefined;
      throw new KoshApiError(
        p ?? { type: 'about:blank', title: response.statusText, status: response.status, detail: text.slice(0, 500) },
      );
    }
    return { body: body as T, headers: response.headers };
  }

  const versioned = async <T>(pending: Promise<{ body: T; headers: Headers }>): Promise<Versioned<T>> => {
    const { body, headers } = await pending;
    return { record: body, etag: headers.get('etag') };
  };
  const writeHeaders = (o: WriteOptions = {}): Record<string, string | undefined> => ({
    'idempotency-key': o.idempotencyKey,
    'if-match': o.ifMatch,
  });

  function model<M extends ModelName>(name: M): ModelClient<M> {
    const root = \`/api/v1/models/\${encodeURIComponent(name)}\`;
    return {
      async list(query = {}) {
        const order = typeof query.order === 'string' ? query.order : query.order?.join(',');
        const { body } = await call<ListResult<never>>('GET', root, {
          query: {
            filter: query.filter === undefined ? undefined : JSON.stringify(query.filter),
            order,
            fields: query.fields?.join(','),
            limit: query.limit === undefined ? undefined : String(query.limit),
            offset: query.offset === undefined ? undefined : String(query.offset),
            count: query.count === true ? 'true' : undefined,
          },
        });
        return body;
      },
      get: (id) => versioned(call('GET', \`\${root}/\${id}\`)),
      create: (values, o) => versioned(call('POST', root, { body: values, headers: writeHeaders(o) })),
      update: (id, values, o) => versioned(call('PATCH', \`\${root}/\${id}\`, { body: values, headers: writeHeaders(o) })),
      async delete(id, o) {
        await call('DELETE', \`\${root}/\${id}\`, { headers: writeHeaders(o) });
      },
      transition: (id, t, o) =>
        versioned(call('POST', \`\${root}/\${id}/transitions/\${encodeURIComponent(t)}\`, { headers: writeHeaders(o) })),
      async aggregate(query) {
        return (await call<{ rows: Record<string, unknown>[] }>('POST', \`\${root}/aggregate\`, { body: query })).body.rows;
      },
      async onchange(input) {
        return (await call<OnchangeResult>('POST', \`\${root}/onchange\`, { body: input })).body;
      },
      async meta() {
        return (await call<ModelMeta>('GET', \`/api/v1/meta/\${encodeURIComponent(name)}\`)).body;
      },
    };
  }

  const auth: AuthClient = {
    async login(login, password) {
      const { body } = await call<SignIn>('POST', '/api/v1/auth/login', { body: { login, password } });
      if (mode === 'bearer') token = body.token;
      else csrf = body.csrfToken;
      return body;
    },
    async verifyTwoFactor(code) {
      await call('POST', '/api/v1/auth/2fa/verify', { body: { code } });
    },
    async logout() {
      await call('POST', '/api/v1/auth/logout');
      token = undefined;
      csrf = undefined;
    },
    async me() {
      return (await call<CurrentUser>('GET', '/api/v1/auth/me')).body;
    },
    async setupTwoFactor() {
      return (await call<{ secret: string; otpauthUri: string }>('POST', '/api/v1/auth/2fa/setup')).body;
    },
    async enableTwoFactor(code) {
      return (await call<{ recoveryCodes: string[] }>('POST', '/api/v1/auth/2fa/enable', { body: { code } })).body;
    },
    async disableTwoFactor(password, code) {
      await call('POST', '/api/v1/auth/2fa/disable', { body: { password, code } });
    },
    async changePassword(current, next) {
      await call('POST', '/api/v1/auth/password', { body: { current, next } });
    },
  };

  return {
    model,
    auth,
    setCompany(next) {
      company = next;
    },
  };
}`;
