/**
 * The generated typed client (RFC 0002 §6.4): generated from the contacts module set without a database, it
 * type-checks as a browser module under the strictest settings (with compile-time errors for wrong fields, models,
 * transitions and missing required values), and runs against a listening server with Bearer and cookie sessions.
 */
import { execFile } from 'node:child_process';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { promisify } from 'node:util';
import { afterAll, beforeAll, describe, expect, test } from 'vitest';
import {
  createServer,
  generateClient,
  installBase,
  type KoshServer,
  openApiOf,
} from '../src/index.js';
import { orm } from '../src/orm.js';
import { contacts } from './fixtures/contacts.js';
import { type Services, startServices } from './support/services.js';

const DIR = resolve(import.meta.dirname, '.generated');
const PASSWORD = 'correct horse battery';

/** Usage the generated types must accept, and mistakes they must reject. */
const USAGE = `import { createClient, KoshApiError, type RecordOf } from './kosh.gen.ts';

const client = createClient({ session: 'bearer', baseUrl: 'http://localhost:3000' });
const partners = client.model('res.partner');

export async function usage(): Promise<void> {
  const { items } = await partners.list({ fields: ['name', 'email'], filter: { isCompany: true }, limit: 10 });
  const first = items[0];
  if (first !== undefined) {
    const id: number = first.id;
    const name: string = first.name;
    const email: string | null | undefined = first.email;
    // @ts-expect-error not requested
    void first.phone;
    void [id, name, email];
  }
  const all = await partners.list({ count: true });
  const stage: 'lead' | 'customer' | 'lost' | undefined = all.items[0]?.stage;
  const total: number | undefined = all.count;
  void [stage, total];

  const { record, etag } = await partners.create({ name: 'Acme', email: null });
  await partners.update(record.id, { phone: '+880 1700 000000' }, etag === null ? {} : { ifMatch: etag });
  await partners.transition(record.id, 'qualify', { idempotencyKey: 'qualify-1' });
  const company: RecordOf<'res.company'> = (await client.model('res.company').get(1)).record;
  void company.currency;

  // @ts-expect-error name is required
  await partners.create({ email: 'x@example.com' });
  // @ts-expect-error unknown field
  await partners.update(1, { nmae: 'x' });
  // @ts-expect-error wrong value type
  await partners.update(1, { isCompany: 'yes' });
  // @ts-expect-error unknown transition
  await partners.transition(1, 'archive');
  // @ts-expect-error no transitions on currencies
  await client.model('res.currency').transition(1, 'x');
  // @ts-expect-error unknown model
  client.model('res.nothing');
  // @ts-expect-error private model
  client.model('auth.session');
  // @ts-expect-error unknown field to select
  await partners.list({ fields: ['nope'] });

  try {
    await partners.get(999);
  } catch (error) {
    if (error instanceof KoshApiError) {
      const status: number = error.status;
      const type: string = error.problem.type;
      void [status, type];
    }
  }
}
`;

/** The web app's compiler settings (browser libraries, no Node types) plus the base strictness. */
const TSCONFIG = {
  compilerOptions: {
    target: 'es2024',
    lib: ['es2024', 'dom', 'dom.iterable'],
    module: 'esnext',
    moduleResolution: 'bundler',
    types: [],
    strict: true,
    exactOptionalPropertyTypes: true,
    noUncheckedIndexedAccess: true,
    noImplicitOverride: true,
    noImplicitReturns: true,
    noPropertyAccessFromIndexSignature: true,
    verbatimModuleSyntax: true,
    isolatedModules: true,
    allowImportingTsExtensions: true,
    noUnusedLocals: true,
    noEmit: true,
    skipLibCheck: true,
  },
  include: ['*.ts'],
};

let code: string;

beforeAll(async () => {
  code = generateClient(openApiOf([contacts]));
  await rm(DIR, { recursive: true, force: true });
  await mkdir(DIR, { recursive: true });
  await writeFile(join(DIR, 'kosh.gen.ts'), code);
  await writeFile(join(DIR, 'usage.ts'), USAGE);
  await writeFile(join(DIR, 'tsconfig.json'), JSON.stringify(TSCONFIG, null, 2));
});

describe('generation', () => {
  test('one interface per model and shape, the Models map, no private models', () => {
    expect(code).toMatch(
      /^\/\/ Generated by `shutro-erp generate client` from "Shutro ERP API" 0\.1\.0\./,
    );
    for (const name of [
      'ResPartner',
      'ResPartnerCreate',
      'ResPartnerUpdate',
      'ResUsers',
      'Problem',
    ])
      expect(code).toContain(`export interface ${name} {`);
    expect(code).toContain('"res.partner": {');
    expect(code).toContain('transitions: "lose" | "qualify";');
    expect(code).toContain('stage: "lead" | "customer" | "lost";');
    expect(code).not.toMatch(/auth\.(session|credential|user_group)|AuthSession|passwordHash/);
  });

  test('deterministic', () => {
    expect(generateClient(openApiOf([contacts]))).toBe(code);
  });

  test('type-checks as a browser module; mistakes are compile errors', async () => {
    const tsc = resolve(import.meta.dirname, '../../../node_modules/typescript/bin/tsc');
    const run = promisify(execFile);
    const result = await run(process.execPath, [tsc, '-p', join(DIR, 'tsconfig.json')]).catch(
      (error: { stdout?: string; stderr?: string }) => ({
        stdout: error.stdout ?? '',
        stderr: error.stderr ?? 'failed',
      }),
    );
    expect(`${result.stdout}${result.stderr}`).toBe(''); // unused @ts-expect-error lines would fail too
  }, 120_000);
});

describe('runtime', () => {
  let services: Services;
  let server: KoshServer;
  let baseUrl: string;
  let client: typeof import('./.generated/kosh.gen.ts');

  beforeAll(async () => {
    services = await startServices();
    server = await createServer({
      databaseUrl: services.databaseUrl,
      modules: [contacts],
      auth: { secureCookies: false, cacheMs: 0 },
      logger: false,
    });
    for (const statement of orm.createTableStatements(server.registry.registry))
      await server.driver.query(statement);
    if (server.auth === undefined) throw new Error('base is installed');
    const { company } = await installBase(server.shutro, server.auth, {
      company: { name: 'Dhaka Ltd', currency: 'BDT' },
      admin: { login: 'admin', name: 'Administrator', password: PASSWORD },
    });
    await server.auth.createUser({
      login: 'alice',
      name: 'Alice',
      password: PASSWORD,
      company,
      companies: [company],
      groups: ['contacts.user'],
    });
    baseUrl = await server.app.listen({ port: 0, host: '127.0.0.1' });
    client = (await import(pathToFileURL(join(DIR, 'kosh.gen.ts')).href)) as typeof client;
  }, 240_000);

  afterAll(async () => {
    await server?.close();
    await services?.stop();
  });

  test('Bearer: sign in, CRUD with ETags, transitions, metadata, problems', async () => {
    const api = client.createClient({ baseUrl, session: 'bearer' });
    await api.auth.login('alice', PASSWORD);
    expect(await api.auth.me()).toMatchObject({ login: 'alice' });
    const partners = api.model('res.partner');

    const { record, etag } = await partners.create({ name: 'Acme', isCompany: true });
    expect(record).toMatchObject({ name: 'Acme', stage: 'lead' });
    expect(etag).toMatch(/^"\d+"$/);
    const updated = await partners.update(
      record.id,
      { phone: '+880' },
      etag === null ? {} : { ifMatch: etag },
    );
    expect(updated.record.phone).toBe('+880');

    // The old ETag is stale now: the server refuses with a typed problem.
    const stale = await partners
      .update(record.id, { phone: '+881' }, etag === null ? {} : { ifMatch: etag })
      .catch((e: unknown) => e);
    expect(stale).toBeInstanceOf(client.KoshApiError);
    expect((stale as InstanceType<typeof client.KoshApiError>).status).toBe(412);

    const { items, count } = await partners.list({
      fields: ['name'],
      filter: { isCompany: true },
      count: true,
    });
    expect(items).toEqual([{ id: record.id, name: 'Acme' }]);
    expect(count).toBe(1);

    expect((await partners.transition(record.id, 'qualify')).record.stage).toBe('customer');
    const meta = await partners.meta();
    expect(meta.operations).toMatchObject({ read: true, unlink: false });
    expect(meta.fields.some((f) => f.key === 'creditLimit')).toBe(false); // managers only

    const forbidden = await partners.delete(record.id).catch((e: unknown) => e);
    expect((forbidden as InstanceType<typeof client.KoshApiError>).problem.type).toBe(
      'https://kosh.dev/problems/access',
    );

    await api.auth.logout();
    const after = await api.auth.me().catch((e: unknown) => e);
    expect((after as InstanceType<typeof client.KoshApiError>).status).toBe(401);
  });

  test('cookie session: the client sends the CSRF token it received', async () => {
    let jar = '';
    const cookieFetch: typeof fetch = async (input, init) => {
      const headers = new Headers(init?.headers);
      if (jar !== '') headers.set('cookie', jar);
      const response = await fetch(input, { ...init, headers });
      const set = response.headers.get('set-cookie');
      if (set !== null) jar = set.split(';')[0] ?? '';
      return response;
    };
    const api = client.createClient({ baseUrl, fetch: cookieFetch });
    await api.auth.login('alice', PASSWORD);
    expect(jar).toMatch(/^kosh_session=/);
    const { record } = await api.model('res.partner').create({ name: 'Cookie Ltd' });
    expect(record.name).toBe('Cookie Ltd');

    // Without the CSRF token, the same cookie cannot change data.
    const bare = client.createClient({ baseUrl, fetch: cookieFetch });
    const refused = await bare
      .model('res.partner')
      .create({ name: 'Forged' })
      .catch((e: unknown) => e);
    expect((refused as InstanceType<typeof client.KoshApiError>).problem.type).toBe(
      'https://kosh.dev/problems/csrf',
    );
  });
});
