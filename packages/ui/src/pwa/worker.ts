/**
 * The service worker's source, one copy for every Kosh app (RFC 0010 Phase B, RFC 0006 §5.4): the app shell
 * offline (the built assets are cached at install; a navigation falls back to the cached shell when the network
 * is gone) and web push. The Vite plugin (`@kosh/ui/vite`) builds it with the bundle's asset list; in development
 * it has none, so nothing is cached and push still works. `/api/` is never cached: data offline is the query
 * cache's business (`offline/persist.ts`).
 */

export interface WorkerConfig {
  /** Changes with every build: a new worker installs and old caches go. */
  readonly version: string;
  /** Absolute paths of the shell and its assets. */
  readonly assets: readonly string[];
}

/** The worker's JavaScript. */
export function serviceWorkerSource(config: WorkerConfig): string {
  return `/* Shutro ERP service worker ${config.version}: generated by @kosh/ui/vite, do not edit. */
const VERSION = ${JSON.stringify(config.version)};
const ASSETS = ${JSON.stringify(config.assets)};
const CACHE = 'kosh-' + VERSION;
const SHELL = '/index.html';

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => (ASSETS.length === 0 ? undefined : cache.addAll(ASSETS)))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k.startsWith('kosh-') && k !== CACHE).map((k) => caches.delete(k))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;
  if (request.mode === 'navigate') {
    // The shell: the network when it answers, the cached copy when it does not (offline, or the server is down).
    event.respondWith(
      fetch(request).catch(() =>
        caches.match(SHELL, { ignoreVary: true }).then((hit) => hit ?? Response.error()),
      ),
    );
    return;
  }
  if (ASSETS.includes(url.pathname)) {
    // Hashed assets never change under a name: the cache first. ignoreVary: servers answer them with
    // "Vary: Origin", which would make a module script's request miss the copy cached at install.
    event.respondWith(
      caches.match(request, { ignoreVary: true }).then((hit) => hit ?? fetch(request)),
    );
  }
});

self.addEventListener('push', (event) => {
  let data = { title: 'Shutro ERP', body: '', url: '/', id: 0 };
  try {
    data = { ...data, ...event.data.json() };
  } catch {
    // not JSON: shown as is
  }
  event.waitUntil(
    self.registration.showNotification(data.title, {
      body: data.body,
      icon: '/icon.svg',
      badge: '/icon.svg',
      data: { url: data.url, id: data.id },
      tag: 'kosh-' + data.id,
    }),
  );
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const url = new URL((event.notification.data && event.notification.data.url) || '/', self.location.origin).href;
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((clients) => {
      const open = clients.find((c) => c.url.startsWith(self.location.origin));
      if (open !== undefined) {
        open.focus();
        return open.navigate(url);
      }
      return self.clients.openWindow(url);
    }),
  );
});
`;
}
