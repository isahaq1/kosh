/**
 * The Studio generator (RFC 0012 §5.2): a spec becomes the module's files, deterministically (the same spec gives
 * the same bytes). `models.ts` holds the Shutro side (extensions of other modules' models, the module's own
 * models, its groups), `index.ts` the Kosh manifest (access levels, views and their extensions, menus, actions,
 * approvals), `README.md` what the module changes, for reviewers. Imports point at `shutro-erp` (an installation)
 * or at the workspace packages (`@kosh/…`, the tests).
 */
import {
  camel,
  modelName,
  pascal,
  prefixedKey,
  type StudioField,
  type StudioSpec,
  validateSpec,
} from './spec.js';

export interface GenerateOptions {
  /** `shutro-erp` (default): an installation's imports; `workspace`: this repository's packages. */
  readonly imports?: 'shutro-erp' | 'workspace';
  /** Where a dependency is imported from, when not the default (`shutro-erp/<name>`, `@kosh/<name>`). */
  readonly moduleImport?: ((name: string) => string | undefined) | undefined;
  /** The extension of the module's own imports (default: `.ts` for `shutro-erp`, `.js` for `workspace`). */
  readonly extension?: '.ts' | '.js';
}

export class StudioSpecError extends Error {
  constructor(readonly problems: readonly string[]) {
    super(`The Studio spec is not valid:\n- ${problems.join('\n- ')}`);
    this.name = 'StudioSpecError';
  }
}

const HEADER =
  '// Generated by Shutro ERP Studio from studio.json: do not edit (edit studio.json, then `shutro-erp studio build`).';

/** A TypeScript literal with single quotes and stable key order (as given). */
export function lit(value: unknown, indent = ''): string {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'string')
    return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return `[${value.map((v) => lit(v, indent)).join(', ')}]`;
  }
  const entries = Object.entries(value as Record<string, unknown>).filter(
    ([, v]) => v !== undefined,
  );
  if (entries.length === 0) return '{}';
  const inner = `${indent}  `;
  const key = (k: string) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : lit(k));
  return `{\n${entries.map(([k, v]) => `${inner}${key(k)}: ${lit(v, inner)},`).join('\n')}\n${indent}}`;
}

/** The `f.<type>(…)` call of a field. */
function fieldCall(field: StudioField, indent: string): string {
  const options: Record<string, unknown> = {
    label: field.label,
    required: field.required === true ? true : undefined,
    default: field.default,
    help: field.help,
    tracking: field.tracking === true ? true : undefined,
    groups: field.groups === undefined || field.groups.length === 0 ? undefined : field.groups,
  };
  switch (field.type) {
    case 'selection':
      return `f.selection(${lit(field.options ?? {}, indent)}, ${lit(options, indent)})`;
    case 'many2one':
    case 'many2many':
      return `f.${field.type}(${lit(field.target ?? '')}, ${lit(options, indent)})`;
    case 'decimal':
      return `f.decimal(${lit({ scale: field.scale ?? 2, ...options }, indent)})`;
    case 'monetary':
      return `f.monetary(${lit({ currency: field.currency ?? 'currency', ...options }, indent)})`;
    default:
      return `f.${field.type}(${lit(options, indent)})`;
  }
}

function importsOf(options: GenerateOptions) {
  const workspace = options.imports === 'workspace';
  return {
    base: workspace ? '@kosh/server' : 'shutro-erp',
    orm: workspace ? '@kosh/server/orm' : 'shutro-erp/orm',
    sdk: workspace ? '@kosh/modules-sdk' : 'shutro-erp/modules-sdk',
    views: workspace ? '@kosh/views' : 'shutro-erp/views',
    module: (name: string) =>
      options.moduleImport?.(name) ?? (workspace ? `@kosh/${name}` : `shutro-erp/${name}`),
    ext: options.extension ?? (workspace ? '.js' : '.ts'),
  };
}

/** The model a view id belongs to: the id without its last segment (`res.partner.form` → `res.partner`). */
export const viewModel = (view: string): string => view.slice(0, view.lastIndexOf('.'));

/** The module's files from its spec. @throws {StudioSpecError} when the spec is not valid */
export function generateModule(
  spec: StudioSpec,
  options: GenerateOptions = {},
): Readonly<Record<string, string>> {
  const problems = validateSpec(spec);
  if (problems.length > 0) throw new StudioSpecError(problems);
  const im = importsOf(options);
  const name = spec.name;
  const id = camel(name);
  const deps = [...new Set(spec.depends)].filter((d) => d !== 'base').sort();

  // models.ts: the extensions by model (one per model), the own models, the module.
  const byModel = new Map<string, StudioField[]>();
  for (const field of spec.fields ?? []) {
    const list = byModel.get(field.model) ?? [];
    list.push(field);
    byModel.set(field.model, list);
  }
  const extensionName = (model: string) => `${pascal(model.replace(/\./g, '_'))}Studio`;
  const ownName = (local: string) => pascal(local);
  const lines: string[] = [
    HEADER,
    `/** The Shutro side of ${spec.label}: fields on other modules' models, models of its own, its groups. */`,
  ];
  const shutroDeps = deps.map((d) => `${camel(d)}Shutro`);
  lines.push(`import { baseShutro } from '${im.base}';`);
  for (const d of deps) lines.push(`import { ${camel(d)}Shutro } from '${im.module(d)}';`);
  lines.push(
    `import { orm } from '${im.orm}';`,
    '',
    'const { defineGroup, defineModel, defineModule, extendModel, f } = orm;',
    '',
  );
  for (const [model, fields] of byModel) {
    lines.push(`export const ${extensionName(model)} = extendModel('${model}', {`, '  fields: {');
    for (const field of fields)
      lines.push(`    ${prefixedKey(name, field.name)}: ${fieldCall(field, '    ')},`);
    lines.push('  },', '});', '');
  }
  for (const m of spec.models ?? []) {
    const full = modelName(name, m.name);
    const recName = m.recName ?? m.fields.find((f) => f.type === 'char')?.name;
    lines.push(`export const ${ownName(m.name)} = defineModel('${full}', {`);
    lines.push(`  label: ${lit(m.label)},`);
    if (recName !== undefined) lines.push(`  recName: '${recName}',`);
    if (m.archivable === true) lines.push('  archivable: true,');
    if (m.companyScoped === true) lines.push('  companyScoped: { required: true },');
    lines.push(
      '  access: {',
      `    '${name}.user': ['read', 'write', 'create'],`,
      `    '${name}.manager': ['read', 'write', 'create', 'unlink', 'export', 'import'],`,
      '  },',
      '  fields: {',
    );
    for (const field of m.fields) lines.push(`    ${field.name}: ${fieldCall(field, '    ')},`);
    lines.push('  },', '});', '');
  }
  lines.push(
    `export const ${id}Shutro: ReturnType<typeof defineModule> = defineModule({`,
    `  name: '${name}',`,
    `  version: '${spec.version}',`,
    `  depends: [${['baseShutro', ...shutroDeps].join(', ')}],`,
    '  groups: [',
    `    defineGroup({ code: '${name}.user', label: ${lit(`${spec.label} user`)}, implies: ['base.user'] }),`,
    `    defineGroup({ code: '${name}.manager', label: ${lit(`${spec.label} manager`)}, implies: ['${name}.user'] }),`,
    '  ],',
    `  models: [${(spec.models ?? []).map((m) => ownName(m.name)).join(', ')}],`,
    `  extensions: [${[...byModel.keys()].map(extensionName).join(', ')}],`,
    '});',
    '',
  );
  const modelsTs = lines.join('\n');

  // index.ts: the manifest.
  const own = new Map((spec.models ?? []).map((m) => [modelName(name, m.name), m]));
  const keyOn = (model: string, field: string): string => {
    if (own.has(model)) return field;
    return (spec.fields ?? []).some((f) => f.model === model && f.name === field)
      ? prefixedKey(name, field)
      : field;
  };
  const views: string[] = [];
  const searches: string[] = [];
  for (const [full, m] of own) {
    const keys = m.fields.map((f) => f.name);
    views.push(
      `    '${full}.list': list('${full}', { columns: ${lit(keys.slice(0, 6))} }),`,
      `    '${full}.form': form('${full}', (k) => ({ sheet: [k.group('main', ${lit(keys)})] })),`,
    );
    const text = m.fields.filter((f) => f.type === 'char' || f.type === 'text').map((f) => f.name);
    if (text.length > 0)
      searches.push(`    '${full}': search('${full}', { fields: ${lit(text.slice(0, 3))} }),`);
  }
  const extensions = (spec.viewChanges ?? []).map((change) => {
    const model = viewModel(change.view);
    const ops = change.operations.map((op) => {
      if ('remove' in op) return `{ remove: '${op.remove}' }`;
      if ('setAttrs' in op)
        return `{ setAttrs: '${op.setAttrs}', attrs: ${lit(op.attrs, '        ')} }`;
      const [verb, anchor] =
        'insertAfter' in op
          ? ['insertAfter', op.insertAfter]
          : 'insertBefore' in op
            ? ['insertBefore', op.insertBefore]
            : ['append', op.append];
      const nodes = op.fields.map((f) => {
        const key = keyOn(model, f);
        return `field({ field: '${key}', id: '${key}' })`;
      });
      return `{ ${verb}: '${anchor}', nodes: [${nodes.join(', ')}] }`;
    });
    return `    {\n      view: '${change.view}',\n      operations: [\n        ${ops.join(',\n        ')},\n      ],\n    },`;
  });
  const actions: string[] = [];
  const menus: string[] = [];
  if (spec.app !== undefined)
    menus.push(`    { id: '${name}.root', label: ${lit(spec.app.label)}, app: '${name}' },`);
  for (const menu of spec.menus ?? []) {
    const model = own.has(modelName(name, menu.model)) ? modelName(name, menu.model) : menu.model;
    const action = `${name}.action_${menu.id}`;
    actions.push(
      `    '${action}': { model: '${model}', label: ${lit(menu.label)}, views: ${lit(menu.views ?? ['list', 'form'])} },`,
    );
    menus.push(
      `    { id: '${name}.${menu.id}', parent: '${menu.parent ?? `${name}.root`}', label: ${lit(menu.label)}, action: '${action}'${menu.sequence === undefined ? '' : `, sequence: ${menu.sequence}`} },`,
    );
  }
  const viewImports = [
    extensions.length > 0 ? 'field' : null,
    own.size > 0 ? 'form' : null,
    own.size > 0 ? 'list' : null,
    searches.length > 0 ? 'search' : null,
  ].filter((x) => x !== null);
  const index = [
    HEADER,
    '/**',
    ` * ${spec.label}${spec.description === undefined ? '' : `: ${spec.description}`}`,
    ' * A Shutro ERP Studio module (RFC 0012): its fields, models, view changes, menus, approvals and rules, from studio.json.',
    ' */',
    `import { base } from '${im.base}';`,
    ...deps.map((d) => `import { ${camel(d)} } from '${im.module(d)}';`),
    `import { defineModule } from '${im.sdk}';`,
    ...(viewImports.length > 0 ? [`import { ${viewImports.join(', ')} } from '${im.views}';`] : []),
    `import { ${id}Shutro } from './models${im.ext}';`,
    '',
    `export { ${[`${id}Shutro`, ...[...byModel.keys()].map(extensionName), ...(spec.models ?? []).map((m) => ownName(m.name))].join(', ')} } from './models${im.ext}';`,
    '',
    `export const ${id}: ReturnType<typeof defineModule> = defineModule({`,
    `  shutro: ${id}Shutro,`,
    "  kosh: '^0.1.0',",
    `  depends: [${['base', ...deps.map(camel)].join(', ')}],`,
    ...(spec.app === undefined
      ? []
      : [
          `  app: { code: '${name}', label: ${lit(spec.app.label)}, icon: ${lit(spec.app.icon ?? 'box')}, sequence: 60 },`,
        ]),
    '  accessLevels: {',
    `    user: { label: 'User', groups: ['${name}.user'] },`,
    `    manager: { label: 'Manager', groups: ['${name}.manager'], implies: ['user'] },`,
    '  },',
    ...(actions.length === 0 ? [] : ['  actions: {', ...actions, '  },']),
    ...(menus.length === 0 ? [] : ['  menus: [', ...menus, '  ],']),
    ...(views.length === 0 ? [] : ['  views: {', ...views, '  },']),
    ...(searches.length === 0 ? [] : ['  search: {', ...searches, '  },']),
    ...(extensions.length === 0 ? [] : ['  viewExtensions: [', ...extensions, '  ],']),
    ...((spec.approvals ?? []).length === 0 ? [] : [`  approvals: ${lit(spec.approvals, '  ')},`]),
    ...((spec.automationRules ?? []).length === 0
      ? []
      : [
          `  automationRules: ${lit(
            Object.fromEntries(
              (spec.automationRules ?? []).map(({ id: key, ...rule }) => [key, rule]),
            ),
            '  ',
          )},`,
        ]),
    '});',
    '',
  ].join('\n');

  // README.md: for reviewers.
  const readme = [
    `# ${spec.label} (\`${name}\` ${spec.version})`,
    '',
    'A Shutro ERP Studio module (RFC 0012): `studio.json` is its source; `index.ts` and `models.ts` are generated from it',
    '(`shutro-erp studio build`). To take it over as code, delete `studio.json` and edit the TypeScript.',
    '',
    ...(spec.description === undefined ? [] : [spec.description, '']),
    ...((spec.fields ?? []).length === 0
      ? []
      : [
          '## Fields on other models',
          '',
          ...(spec.fields ?? []).map(
            (f) =>
              `- \`${f.model}.${prefixedKey(name, f.name)}\`: ${f.label} (${f.type}${f.required ? ', required' : ''})`,
          ),
          '',
        ]),
    ...((spec.models ?? []).length === 0
      ? []
      : [
          '## Models',
          '',
          ...(spec.models ?? []).map(
            (m) =>
              `- \`${modelName(name, m.name)}\`: ${m.label} (${m.fields.map((f) => f.name).join(', ')})`,
          ),
          '',
        ]),
    ...((spec.viewChanges ?? []).length === 0
      ? []
      : [
          '## View changes',
          '',
          ...(spec.viewChanges ?? []).map(
            (v) => `- \`${v.view}\`: ${v.operations.length} change(s)`,
          ),
          '',
        ]),
    ...((spec.menus ?? []).length === 0
      ? []
      : ['## Menus', '', ...(spec.menus ?? []).map((m) => `- ${m.label} (\`${m.model}\`)`), '']),
    ...((spec.approvals ?? []).length === 0
      ? []
      : [
          '## Approval policies',
          '',
          ...(spec.approvals ?? []).map((a) => `- ${a.name} on \`${a.model}\``),
          '',
        ]),
    ...((spec.automationRules ?? []).length === 0
      ? []
      : [
          '## Automation rules',
          '',
          ...(spec.automationRules ?? []).map(
            (r) => `- \`${r.id}\`: ${r.name} (\`${r.model}\`, ${r.trigger})`,
          ),
          '',
        ]),
  ].join('\n');

  return {
    'models.ts': modelsTs,
    'index.ts': index,
    'README.md': readme,
  };
}
